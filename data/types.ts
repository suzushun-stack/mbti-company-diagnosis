export function getTypeCode(scores: {
  stability: number;
  team: number;
  org: number;
  domain: number;
}): string {
  const s = scores.stability <= 0 ? 'S' : 'G';
  const t = scores.team <= 0 ? 'T' : 'I';
  const o = scores.org <= 0 ? 'K' : 'V';
  const d = scores.domain <= 0 ? 'M' : 'H';
  return `${s}-${t}-${o}-${d}`;
}
